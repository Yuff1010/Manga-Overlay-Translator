"""Slow OCR fixture test: run the real OCR pipeline on a generated image.

Opt-in by design — it loads PaddleOCR and may download models on first use:

    OCRT_SLOW=1 python server/tests/test_ocr_fixture.py        (bash)
    set OCRT_SLOW=1 && python server/tests/test_ocr_fixture.py (Windows cmd)

Skips (exit 0) when OCRT_SLOW is unset or paddleocr is not installed, so it
never disturbs the fast test loop. The image is generated by PIL from plain
ASCII text, so it contains no copyrighted content.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

if os.getenv("OCRT_SLOW") != "1":
    print("SKIP: set OCRT_SLOW=1 to run the slow OCR fixture test")
    sys.exit(0)

try:
    import paddleocr  # noqa: F401
except ImportError:
    print("SKIP: paddleocr not installed in this environment")
    sys.exit(0)

from PIL import Image, ImageDraw, ImageFont  # noqa: E402

import numpy as np  # noqa: E402

from ocr import run_ocr  # noqa: E402

WORDS = ["HELLO", "MANGA", "12345"]


def _font(size):
    for name in ("arial.ttf", "Arial.ttf", "DejaVuSans.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    try:                       # Pillow >= 10：矢量默认字体
        return ImageFont.load_default(size=size)
    except TypeError:
        return ImageFont.load_default()


def main():
    img = Image.new("RGB", (900, 360), "white")
    d = ImageDraw.Draw(img)
    font = _font(56)
    for i, w in enumerate(WORDS):
        d.text((60, 30 + i * 110), w, fill="black", font=font)

    blocks = run_ocr(np.array(img), "en")
    joined = " ".join(b["text"] for b in blocks).upper()
    print(f"OCR blocks: {[b['text'] for b in blocks]}")

    fails = []
    for w in WORDS:
        if w not in joined:
            fails.append(w)
        print(f"[{'PASS' if w in joined else 'FAIL'}] fixture text recognized: {w}")

    # 坐标约束：全部落在原图范围内（切片偏移错了会越界）
    ok_xy = all(
        b["x"] >= 0 and b["y"] >= 0
        and b["x"] + b["w"] <= 900 and b["y"] + b["h"] <= 360
        for b in blocks
    )
    print(f"[{'PASS' if ok_xy else 'FAIL'}] boxes within image bounds")
    if not ok_xy:
        fails.append("bounds")

    if fails:
        print(f"RESULT: FAILED -> {fails}")
        return 1
    print("RESULT: ALL PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
